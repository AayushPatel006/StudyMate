import { useCallback, useEffect, useRef, useState } from 'react';
import { Link, useNavigate, useSearchParams } from 'react-router-dom';
import { WandSparkles, CalendarDays, List, Sparkles, Cpu, TriangleAlert, CircleAlert, Info, RefreshCw, ListChecks, Clock, CircleCheck, Target } from 'lucide-react';
import { Button, Card, EmptyState, PageHeader, PageLoader, Segmented, cx } from '../components/ui/index.jsx';
import WeekCalendar from '../components/planner/WeekCalendar.jsx';
import SessionList from '../components/planner/SessionList.jsx';
import SessionModal from '../components/planner/SessionModal.jsx';
import GeneratingState from '../components/planner/GeneratingState.jsx';
import { api, errorMessage, errorCode } from '../api/client.js';
import { useToast } from '../context/ToastContext.jsx';
import { formatDateLabel, formatDuration, PRIORITY_STYLES } from '../utils/format.js';

const WARNING_STYLES = {
  error: { box: 'border-rose-200 bg-rose-50 text-rose-800', icon: CircleAlert, iconCls: 'text-rose-500' },
  warning: { box: 'border-amber-200 bg-amber-50 text-amber-900', icon: TriangleAlert, iconCls: 'text-amber-500' },
  info: { box: 'border-slate-200 bg-slate-50 text-slate-700', icon: Info, iconCls: 'text-slate-400' },
};

function GenerateButton({ onClick, loading, hasPlan, size = 'md', disabled }) {
  return (
    <Button variant="brand" size={size} icon={hasPlan ? RefreshCw : WandSparkles} onClick={onClick} loading={loading} disabled={disabled}>
      {hasPlan ? 'Regenerate Plan' : 'Generate My Study Plan'}
    </Button>
  );
}

function PlanSourceBanner({ plan }) {
  const ai = plan.generatedBy === 'gemini';
  return (
    <div className={cx('flex flex-col gap-3 rounded-xl border p-4 sm:flex-row sm:items-center', ai ? 'border-violet-200 bg-gradient-to-r from-indigo-50 via-violet-50 to-fuchsia-50' : 'border-amber-200 bg-amber-50/70')}>
      <div className={cx('flex size-10 shrink-0 items-center justify-center rounded-xl', ai ? 'ai-gradient text-white' : 'bg-amber-100 text-amber-700')}>
        {ai ? <Sparkles className="size-5" /> : <Cpu className="size-5" />}
      </div>
      <div className="min-w-0 flex-1">
        <p className="text-sm font-semibold text-slate-900">
          {ai ? (
            <>
              Generated by <span className="ai-text">Gemini</span> <span className="font-normal text-slate-500">· {plan.model} · free tier</span>
            </>
          ) : (
            <>Fallback mode — built-in scheduling algorithm</>
          )}
        </p>
        <p className="mt-0.5 text-sm text-slate-600">{ai ? plan.summary : plan.fallbackReason || plan.summary}</p>
      </div>
      <div className="flex shrink-0 gap-4 text-xs text-slate-500 sm:flex-col sm:items-end sm:gap-0.5">
        <span>Version {plan.version}</span>
        <span>{new Date(plan.createdAt).toLocaleString(undefined, { month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' })}</span>
      </div>
    </div>
  );
}

export default function PlannerPage() {
  const toast = useToast();
  const navigate = useNavigate();
  const [params, setParams] = useSearchParams();
  const [state, setState] = useState(null); // { plan, sessions }
  const [readiness, setReadiness] = useState(null);
  const [availability, setAvailability] = useState(null);
  const [aiStatus, setAiStatus] = useState(null);
  const [generating, setGenerating] = useState(false);
  const [view, setView] = useState(() => (typeof window !== 'undefined' && window.innerWidth < 768 ? 'list' : 'calendar'));
  const [selected, setSelected] = useState(null);
  const autoRan = useRef(false);

  const load = useCallback(async () => {
    try {
      const [planRes, dashRes, availRes, aiRes] = await Promise.all([api.get('/plans/active'), api.get('/dashboard'), api.get('/availability'), api.get('/ai/status')]);
      setState(planRes.data);
      setReadiness({ tasks: dashRes.data.stats.activeTasks, availability: dashRes.data.availabilityConfigured });
      setAvailability(availRes.data.availability);
      setAiStatus(aiRes.data);
    } catch (err) {
      toast.error('Could not load your plan', errorMessage(err));
      setState((s) => s || { plan: null, sessions: [] });
    }
  }, [toast]);

  useEffect(() => {
    load();
  }, [load]);

  const generate = useCallback(async () => {
    setGenerating(true);
    try {
      const res = await api.post('/plans/generate');
      setState({ plan: res.data.plan, sessions: res.data.sessions });
      const { plan } = res.data;
      const problems = plan.warnings.filter((w) => w.severity !== 'info').length;
      if (plan.generatedBy === 'gemini') toast.success('Your AI study plan is ready', `${plan.stats.totalSessions} sessions planned with Gemini.${problems ? ` ${problems} warning(s) to review.` : ''}`);
      else toast.info('Plan ready (fallback mode)', plan.fallbackReason);
      load();
    } catch (err) {
      const code = errorCode(err);
      toast.error('Could not generate a plan', errorMessage(err));
      if (code === 'NO_AVAILABILITY') navigate('/availability');
    } finally {
      setGenerating(false);
    }
  }, [toast, load, navigate]);

  // Dashboard quick action: /planner?generate=1
  useEffect(() => {
    if (params.get('generate') === '1' && readiness && !autoRan.current) {
      autoRan.current = true;
      setParams({}, { replace: true });
      if (readiness.tasks && readiness.availability) generate();
    }
  }, [params, readiness, generate, setParams]);

  if (!state || !readiness) return <PageLoader />;

  const { plan, sessions } = state;
  const ready = readiness.tasks > 0 && readiness.availability;
  const totalMinutes = sessions.reduce((a, s) => a + s.duration, 0);
  const taskCount = new Set(sessions.map((s) => s.taskId)).size;
  const severeWarnings = plan?.warnings.filter((w) => w.severity !== 'info') || [];
  const infoWarnings = plan?.warnings.filter((w) => w.severity === 'info') || [];

  return (
    <div className="animate-fade-in">
      <PageHeader
        title="Study Planner"
        description={plan ? `Week of ${formatDateLabel(plan.windowStart, { month: 'long', day: 'numeric' })} – ${formatDateLabel(plan.windowEnd, { month: 'long', day: 'numeric' })}` : 'Turn your tasks and free time into a realistic weekly schedule.'}
        actions={plan && !generating && <GenerateButton onClick={generate} loading={generating} hasPlan />}
      />

      {generating ? (
        <GeneratingState aiEnabled={aiStatus?.configured} />
      ) : !plan ? (
        <Card className="overflow-hidden">
          <div className="relative px-6 py-14 text-center sm:py-20">
            <div className="ai-gradient absolute top-0 left-1/2 size-80 -translate-x-1/2 -translate-y-1/2 rounded-full opacity-[0.08] blur-3xl" />
            <div className="relative mx-auto max-w-lg">
              <div className="ai-gradient mx-auto flex size-14 items-center justify-center rounded-2xl text-white shadow-[0_10px_30px_-10px_rgb(99_102_241/0.9)]">
                <WandSparkles className="size-6" />
              </div>
              <h2 className="mt-5 text-xl font-semibold tracking-tight text-slate-900">Your week, planned in seconds</h2>
              <p className="mt-2 text-sm leading-relaxed text-slate-500">
                StudyMate {aiStatus?.configured ? 'asks Gemini to prioritize' : 'prioritizes'} your tasks by deadline and importance, splits big assignments into focused sessions, and fits them into your free time — then checks every session against your rules.
              </p>
              <div className="mx-auto mt-7 grid max-w-sm gap-2 text-left">
                <Link to="/tasks" className="flex items-center gap-3 rounded-lg border border-slate-200 bg-white px-3 py-2.5 text-sm hover:border-slate-300">
                  {readiness.tasks > 0 ? <CircleCheck className="size-5 text-emerald-500" /> : <ListChecks className="size-5 text-slate-400" />}
                  <span className="flex-1 text-slate-700">{readiness.tasks > 0 ? `${readiness.tasks} active task${readiness.tasks === 1 ? '' : 's'}` : 'Add at least one task'}</span>
                </Link>
                <Link to="/availability" className="flex items-center gap-3 rounded-lg border border-slate-200 bg-white px-3 py-2.5 text-sm hover:border-slate-300">
                  {readiness.availability ? <CircleCheck className="size-5 text-emerald-500" /> : <Clock className="size-5 text-slate-400" />}
                  <span className="flex-1 text-slate-700">{readiness.availability ? 'Availability saved' : 'Set your weekly availability'}</span>
                </Link>
              </div>
              <div className="mt-7">
                <GenerateButton onClick={generate} loading={generating} hasPlan={false} size="lg" disabled={!ready} />
                {!ready && <p className="mt-3 text-xs text-slate-500">Complete the steps above first.</p>}
              </div>
            </div>
          </div>
        </Card>
      ) : (
        <div className="space-y-5">
          {plan.stale && (
            <div className="flex flex-col gap-3 rounded-xl border border-sky-200 bg-sky-50 px-4 py-3 sm:flex-row sm:items-center">
              <RefreshCw className="size-4 shrink-0 text-sky-600" />
              <p className="flex-1 text-sm text-sky-900">Your tasks or availability changed after this plan was generated. Regenerate to include the latest changes.</p>
              <Button size="sm" variant="secondary" onClick={generate}>
                Regenerate now
              </Button>
            </div>
          )}

          <PlanSourceBanner plan={plan} />

          {severeWarnings.length > 0 && (
            <div className="space-y-2">
              {severeWarnings.map((w, i) => {
                const st = WARNING_STYLES[w.severity];
                return (
                  <div key={i} className={cx('flex items-start gap-3 rounded-xl border px-4 py-3 text-sm', st.box)} role="alert">
                    <st.icon className={cx('mt-0.5 size-4 shrink-0', st.iconCls)} />
                    <span>{w.message}</span>
                  </div>
                );
              })}
            </div>
          )}

          <div className="grid grid-cols-1 gap-5 2xl:grid-cols-[1fr_300px]">
            <Card className="min-w-0 overflow-hidden">
              <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-100 px-4 py-3 sm:px-5">
                <div className="flex items-center gap-4 text-sm">
                  <span className="font-semibold text-slate-900">{sessions.length} sessions</span>
                  <span className="text-slate-500">{formatDuration(totalMinutes)} total</span>
                  <span className="hidden text-slate-500 sm:inline">{taskCount} task{taskCount === 1 ? '' : 's'}</span>
                </div>
                <div className="flex items-center gap-3">
                  <div className="hidden items-center gap-3 text-xs text-slate-500 md:flex">
                    {['High', 'Medium', 'Low'].map((p) => (
                      <span key={p} className="inline-flex items-center gap-1.5">
                        <span className={cx('size-2 rounded-full', PRIORITY_STYLES[p].dot)} /> {p}
                      </span>
                    ))}
                  </div>
                  <Segmented
                    value={view}
                    onChange={setView}
                    options={[
                      { value: 'calendar', label: 'Calendar', icon: CalendarDays },
                      { value: 'list', label: 'List', icon: List },
                    ]}
                  />
                </div>
              </div>
              {sessions.length === 0 ? (
                <EmptyState icon={CalendarDays} title="No sessions in this plan" description="There was no time available before your deadlines. Check the warnings above, add study hours, or regenerate." />
              ) : view === 'calendar' ? (
                <WeekCalendar windowStart={plan.windowStart} sessions={sessions} availability={availability} onSelect={setSelected} />
              ) : (
                <SessionList windowStart={plan.windowStart} sessions={sessions} onSelect={setSelected} />
              )}
            </Card>

            <div className="grid content-start gap-5 md:grid-cols-2 2xl:grid-cols-1">
              <Card className="p-5">
                <h3 className="flex items-center gap-2 text-sm font-semibold text-slate-900">
                  <Target className="size-4 text-brand-500" /> Priority order
                </h3>
                <p className="mt-0.5 text-xs text-slate-500">{plan.generatedBy === 'gemini' ? 'How Gemini ranked your work' : 'Ranked by deadline, then priority'}</p>
                <ol className="mt-4 space-y-3">
                  {plan.priorities.map((p) => {
                    const taskSessions = sessions.filter((s) => s.taskId === p.taskId);
                    const prio = taskSessions[0]?.priority;
                    return (
                      <li key={p.taskId} className="flex gap-3">
                        <span className="flex size-6 shrink-0 items-center justify-center rounded-md bg-slate-100 text-xs font-semibold text-slate-600">{p.rank}</span>
                        <div className="min-w-0">
                          <p className="flex items-center gap-1.5 truncate text-sm font-medium text-slate-800">
                            {prio && <span className={cx('size-1.5 shrink-0 rounded-full', PRIORITY_STYLES[prio].dot)} />}
                            {p.title}
                          </p>
                          <p className="text-xs leading-snug text-slate-500">{p.reason}</p>
                          <p className="mt-0.5 text-[11px] text-slate-400">
                            {taskSessions.length ? `${taskSessions.length} session${taskSessions.length === 1 ? '' : 's'} · ${formatDuration(taskSessions.reduce((a, s) => a + s.duration, 0))}` : 'Not scheduled this week'}
                          </p>
                        </div>
                      </li>
                    );
                  })}
                </ol>
              </Card>
              {infoWarnings.length > 0 && (
                <Card className="p-5">
                  <h3 className="flex items-center gap-2 text-sm font-semibold text-slate-900">
                    <Info className="size-4 text-slate-400" /> Notes
                  </h3>
                  <ul className="mt-3 space-y-2.5">
                    {infoWarnings.map((w, i) => (
                      <li key={i} className="text-xs leading-relaxed text-slate-600">
                        {w.message}
                      </li>
                    ))}
                  </ul>
                </Card>
              )}
            </div>
          </div>
        </div>
      )}

      <SessionModal session={selected} onClose={() => setSelected(null)} onChanged={load} />
    </div>
  );
}
